async def main() -> None:
    await db.init_db()

    teachers_added = 0
    disciplines_added = 0
    for full_name, disciplines in TEACHERS.items():
        teacher_id = await db.add_teacher(full_name)
        if teacher_id is not None:
            teachers_added += 1
        else:
            found = await db.search_teachers(full_name, limit=1)
            teacher_id = found[0][0]
        for name in disciplines:
            discipline_id = await db.add_discipline(name)
            if discipline_id is not None:
                disciplines_added += 1
            else:
                found = await db.search_disciplines(name, limit=50)
                discipline_id = next(
                    d_id for d_id, d_name in found if d_name.lower() == name.lower()
                )
            await db.link_teacher_discipline(teacher_id, discipline_id)

    reviews_added = 0
    for i, (name, loyalty, difficulty, clarity, text) in enumerate(REVIEWS, start=1):
        found = await db.search_teachers(name, limit=1)
        if not found:
            print(f"!! преподаватель не найден: {name}")
            continue
        teacher_id = found[0][0]
        # не плодим дубликаты при повторном запуске
        if len(await db.approved_reviews(teacher_id, limit=100)) >= 2 and i > 6:
            continue
        await db.create_review(
            teacher_id=teacher_id,
            user_id=100000 + i,
            username=f"student{i}",
            loyalty=loyalty,
            difficulty=difficulty,
            clarity=clarity,
            text=text,
            status="approved",
        )
        reviews_added += 1

    print(f"Преподавателей добавлено: {teachers_added} (всего в базе: {len(TEACHERS)})")
    print(f"Дисциплин добавлено: {disciplines_added}")
    print(f"Отзывов добавлено: {reviews_added}")
    print("Итог:", await db.stats())


if __name__ == "__main__":
    asyncio.run(main())
